// 動画でワークフローのプロンプトで共通して使う部分。
// 「守ること（セキュリティ）」「出力の形」「再現のための決まり」は全ワークフローで同じ文面にして、
// ここを直せば全ページに反映されるようにしている。

// セキュリティと、AI に嘘をつかせないための決まり。どのプロンプトにも必ず入れる。
export const RULES = `# 必ず守ること
1. 事実は公共データベースから取得し、出典（データベース名・ID・URL・参照した日）を必ず併記する。
2. 確認できなかった項目は「未確認」と書く。推測で埋めない。ID・論文・数値を作らない。
3. 未公開データ・個人情報・患者さんの情報が入力に含まれていたら、作業を止めて指摘する。
4. 読むだけにする。指示にない外部サイトへの送信・投稿・書き込みはしない。
5. 要ログイン・有料のデータベースは、その旨を書いたうえで、代わりに使える公開データベースを示す。
6. 医療上の判断（診断・治療・検査の要否）の助言はしない。研究目的の情報整理に限る。`;

// 出力の形。毎回同じ形で出させることで、再実行したときに見比べられるようにする。
export const OUTPUT = `# 出力の形（毎回この形で出す）
## 1. 要約（3行以内）
## 2. 調査結果
| STEP | 調べたこと | 結果 | 出典（DB・ID・URL） | 参照日 |
## 3. 解釈が分かれる点／未確認の項目
## 4. 次に確かめるとよいこと
## 5. 実行条件
- モデル名
- MCP 接続の有無と、接続したサーバー名
- 各データベースのバージョン／リリース（分かる範囲で）
- 実行日`;

export const REPRO = `# 再現できるようにするために
- 同じ入力で再実行したときに同じ表になるよう、値には必ず ID とバージョンを添える。
- 数値は丸めず、データベースの表示どおりに書く。
- 検索に使ったクエリ（検索語・絞り込み条件）をそのまま残す。
- 1ステップずつ進め、結果を表にしてから次のステップへ移る。`;

// ワークフローごとの定義から、貼り付け用のプロンプト本文を組み立てる。
export function buildPrompt(def) {
  const parts = [
    "# 役割\n" + def.role + "\n統合TV「動画でワークフロー：" + def.pageTitle + "」と同じ順番で調べます。\n" + def.pageUrl,
    "# 入力（ここだけ書き換える）\n" + def.input,
    RULES + (def.extraRules ? "\n" + def.extraRules : ""),
    "# 手順\n" + def.steps,
    OUTPUT,
    REPRO
  ];
  return parts.join("\n\n") + "\n";
}

// ①の結果を記録に変える共通プロンプト。ワークフローによらず同じ。
export const PROMPT_RECORD = `直前の調査結果を、ほかの人が同じ手順をたどれる「再現メモ」として Markdown にまとめてください。

# 書く内容
1. 調べたこと（対象・目的）
2. 実行条件（モデル名／MCP 接続の有無とサーバー名／実行日／データベースのバージョン）
3. 手順の表：STEP、使ったデータベース、検索に使ったクエリや条件、得られた値、出典 ID と URL、参照日
4. 得られた結論と、その確からしさ（確認済み／未確認／解釈が分かれる）
5. 再実行のしかた（同じ結果を得るために必要な入力と設定）
6. 引用（データベースと原著論文）

# 守ること
- 直前の回答に書かれていない値や ID を足さない。確かめていないことは「未確認」と書く。
- 個人情報・未公開データは書かない。
- このメモだけを読んだ人が、同じ順番で同じ検索を再現できる細かさで書く。
`;

// ページに渡す形（タブ2枚）に整える
export function makePrompt(def) {
  return {
    intro: def.intro,
    mcp: def.mcp || [],
    prompts: [
      {
        title: "① 調べる",
        note: def.note || "ChatGPT・Claude などに貼り付けて使います。1行目から最後までをまとめてコピーしてください。",
        body: buildPrompt(def)
      },
      {
        title: "② 再現メモをつくる",
        note: "①の結果が出たあと、続けて貼り付けます。ほかの人が同じ手順をたどれる記録を Markdown で作ります。",
        body: PROMPT_RECORD
      }
    ]
  };
}

